def clean_input(text: str) -> str:
    """Нормализует ввод пользователя: убирает скрытые юникод-символы,
    приводит к нижнему регистру и схлопывает пробелы.

    Используется единообразно во всех обработчиках, чтобы сопоставление
    кнопок никогда не расходилось между модулями.
    """
    if not text:
        return ""
    clean = text.replace("\ufe0f", "").replace("\u200b", "").strip().lower()
    return " ".join(clean.split())


def _normalize_profanity(text: str) -> str:
    """Готовит текст к проверке на мат: латиница/символы -> кириллица,
    удаление разделителей и схлопывание повторов букв."""
    lowered = text.lower().translate(_LOOKALIKE_MAP)
    # Оставляем только буквы и цифры, выкидывая разделители (пробелы, точки, *, _ и т.п.)
    cleaned = re.sub(r"[^\w]+", "", lowered, flags=re.UNICODE)
    # Схлопываем повторы: «ххуууй» -> «хуй»
    collapsed = re.sub(r"(.)\1+", r"\1", cleaned)
    return cleaned, collapsed


def contains_profanity(text: str) -> bool:
    """Возвращает True, если в тексте обнаружена нецензурная лексика.

    Устойчив к обходам через пробелы, повторы букв и латинские «двойники».
    """
    if not text:
        return False
    cleaned, collapsed = _normalize_profanity(text)
    for root in _MAT_ROOTS:
        root_clean, root_collapsed = _normalize_profanity(root)
        if root_clean and (root_clean in cleaned or root_collapsed in collapsed):
            return True
    return False