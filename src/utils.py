"""Общие вспомогательные функции."""


def clean_input(text: str) -> str:
    """Нормализует ввод пользователя: убирает скрытые юникод-символы,
    приводит к нижнему регистру и схлопывает пробелы.

    Используется единообразно во всех обработчиках, чтобы сопоставление
    кнопок никогда не расходилось между модулями.
    """
    if not text:
        return ""
    clean = text.replace("\ufe0f", "").replace("\u200b", "").strip().lower()
    return " ".join(clean.split())